static void flush(lv_display_t *d,const lv_area_t *a,uint8_t *p)
{
  for(int y=a->y1;y<=a->y2;y++){
    memcpy(fb+(y*1024+a->x1)*2,p,(a->x2-a->x1+1)*2);
    p+=(a->x2-a->x1+1)*2;
  }
  lv_display_flush_ready(d);
}
