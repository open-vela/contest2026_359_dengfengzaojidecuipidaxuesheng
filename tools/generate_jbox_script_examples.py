#!/usr/bin/env python3
"""Embed reviewed script source as data; S3 executes the compiled bytecode."""
import json
from pathlib import Path
root=Path(__file__).resolve().parents[1]
source=root/'app/ProgrammableMatrix/client/programs/dht11.jbox'
target=root/'app/espdl-quickapp/overlay/apps/system/desktop/jbox_script_examples.h'
target.write_text('/* Generated by tools/generate_jbox_script_examples.py; do not edit. */\n'
                  'static const char jbox_dht11_source[] = '+json.dumps(source.read_text(encoding='utf-8'))+';\n',encoding='utf-8',newline='\n')
print(target.name)
