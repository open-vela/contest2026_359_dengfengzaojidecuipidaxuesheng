#!/usr/bin/env python3
"""Generate immutable native store seeds; optionally export an SD repository.

The exported repository uses the same strict v1 schema as third-party SD apps.
Do not copy built-in entries to the optional repository at the same time: the
device rejects duplicate identities rather than silently shadowing a source.
"""
import argparse
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'quickapp/store'
TARGET = ROOT / 'app/espdl-quickapp/overlay/apps/system/desktop/glass_app_store_assets.inc'


def generate(export=None, check=False):
    catalog = json.loads((SOURCE / 'catalog.json').read_text(encoding='utf-8'))
    rows, packages, entries = [], set(), []
    assert 0 < len(catalog['headline'].encode('utf-8')) <= 95
    assert 0 < len(catalog['tagline'].encode('utf-8')) <= 127
    for app in catalog['apps']:
        assert re.fullmatch(r'[a-z][a-z0-9_]*', app['id'])
        assert re.fullmatch(r'store\.[a-z0-9_]+', app['package'])
        assert app['package'] not in packages
        for key, maximum in [('package', 47), ('name', 47), ('version', 23), ('summary', 191)]:
            assert 0 < len(app[key].encode('utf-8')) <= maximum
        assert app['category'] in (0, 1, 2)
        packages.add(app['package'])
        data = (SOURCE / app['id'] / 'app.js').read_bytes()
        assert 0 < len(data) <= 65536 and b'\0' not in data
        entry = {k: v for k, v in app.items() if k != 'id'}
        entry.update(bytes=len(data), sha256=hashlib.sha256(data).hexdigest())
        entries.append(entry)
        fields = ','.join('.' + k + '=' + json.dumps(entry[k], ensure_ascii=False) for k in ('package', 'name', 'version', 'summary', 'sha256', 'bytes', 'category'))
        fields += ',.icon=' + str(['calculator','timer','counter','grid'].index(entry.get('icon','grid')))
        literals = '\n'.join(json.dumps(line, ensure_ascii=False) for line in data.decode('utf-8').splitlines(keepends=True))
        rows.append('  {.entry={' + fields + '},.source=\n' + literals + '},')
        if export:
            directory = export / app['package']
            directory.mkdir(parents=True, exist_ok=True)
            (directory / 'app.js').write_bytes(data)
    text = '/* Generated by tools/generate_app_store.py; do not edit. */\nstatic const struct store_seed store_seeds[]={\n' + '\n'.join(rows) + '\n};\n'
    text += 'static const char store_headline[]='+json.dumps(catalog['headline'],ensure_ascii=False)+';\n'
    text += 'static const char store_tagline[]='+json.dumps(catalog['tagline'],ensure_ascii=False)+';\n'
    text += 'static const struct glass_store_feature store_feature_seeds[]={\n'
    assert len(catalog['featured']) <= 2
    for feature in catalog['featured']:
        assert feature['package'] in packages
        for key, maximum in [('title',95),('subtitle',127),('value',23),('unit',23)]:
            assert len(feature.get(key,'').encode('utf-8'))<=maximum
        fields=','.join('.'+key+'='+json.dumps(feature.get(key,''),ensure_ascii=False) for key in ('package','title','subtitle','value','unit'))
        fields+=',.art='+str(['timer','bars','none'].index(feature.get('art','none')))
        fields+=',.tone='+str(['forest','sand','lavender'].index(feature.get('tone','forest')))
        text+='  {'+fields+'},\n'
    text+='};\n'
    if check:
        assert TARGET.read_text(encoding='utf-8') == text, 'Regenerate store assets'
    else:
        TARGET.write_text(text, encoding='utf-8', newline='\n')
    if export:
        exported={k:v for k,v in catalog.items() if k not in ('apps',)}
        exported['apps']=entries
        (export / 'index.json').write_text(json.dumps(exported, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print('STORE_ASSETS_OK', len(entries), sum(e['bytes'] for e in entries), 'source bytes')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--export', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generate(args.export, args.check)
