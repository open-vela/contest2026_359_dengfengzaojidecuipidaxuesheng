#!/usr/bin/env python3
"""Copy WSL NuttX images to the Windows contest tree.

With no arguments this refreshes the current v3.2 NSH files used by the flash
script. A v1.x build requires an explicit output directory outside the repo;
v3 variants stay under the current ``firmware/v3`` entry point.
"""
import argparse
from pathlib import Path
import shutil

src_dir = Path("/home/flash/vela-p4/nuttx")
repo_root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument("--variant", choices=("v1.x", "v3.2", "v3.2-usb"))
parser.add_argument("--output", type=Path, help="required external directory for v1.x")
args = parser.parse_args()

if args.variant == "v1.x":
    if args.output is None:
        parser.error("--variant v1.x requires --output outside this repository")
    dst = args.output.resolve()
    try:
        dst.relative_to(repo_root.resolve())
    except ValueError:
        pass
    else:
        parser.error("--output for v1.x must be outside this repository")
elif args.variant == "v3.2-usb":
    if args.output is not None:
        parser.error("--output is only supported for v1.x")
    dst = repo_root / "firmware/v3/esp32p4-nsh-v3.2-usb"
else:
    if args.output is not None:
        parser.error("--output is only supported for v1.x")
    dst = repo_root / "firmware/v3/esp32p4-nsh-v3.2"
dst.mkdir(parents=True, exist_ok=True)
copied = []
# The final `make` step replaces the temporary objcopy dump with the
# Simple-Boot image generated by the tree's pinned esptool (currently 4.8.1).
# Copy that image verbatim.  Re-running elf2image with newer Windows esptool
# releases can collapse the two entry-address sections and produces an image
# which stalls in the ESP32-P4 ROM/bootloader analog initialization.
if args.variant is None:
    outputs = {
        "nuttx.bin": "nuttx.bin",
        "nuttx.hex": "nuttx.hex",
        "nuttx": "nuttx",
        "nuttx.map": "nuttx.map",
    }
else:
    outputs = {
        "nuttx.bin": f"esp32p4-nsh-{args.variant}.bin",
        "nuttx.hex": f"nuttx-{args.variant}.hex",
        "nuttx": f"nuttx-{args.variant}.elf",
        "nuttx.map": f"nuttx-{args.variant}.map",
        ".config": f"nuttx-{args.variant}.config",
    }

for source_name, output_name in outputs.items():
    s = src_dir / source_name
    if s.exists() and s.is_file():
        shutil.copy2(s, dst / output_name)
        copied.append(f"{output_name} {s.stat().st_size}")
print("DST", dst)
print("COPIED", copied)
image_name = "nuttx.bin" if args.variant is None else f"esp32p4-nsh-{args.variant}.bin"
if not (dst / image_name).exists():
    raise SystemExit("Simple-Boot nuttx.bin missing; build not finished")
