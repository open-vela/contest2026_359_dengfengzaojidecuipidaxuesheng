#!/usr/bin/env python3
"""Subset pinned Noto Sans SC at weight 700 for native CJK/Latin UI headings.

The source is the existing lyric-font lock input; no build-time download.
Requires fontTools. Generated TTF and C data are committed together.
"""
import argparse
import hashlib
import json
from pathlib import Path
from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--source',type=Path,required=True)
    p.add_argument('--license',type=Path,required=True)
    a=p.parse_args();repo=Path(__file__).resolve().parents[1]
    lock=json.loads((repo/'app/espdl-quickapp/assets/lyric-fonts.lock.json').read_text())
    expected=lock['files']['notosanssc/NotoSansSC[wght].ttf']['sha256']
    assert hashlib.sha256(a.source.read_bytes()).hexdigest()==expected,'Pinned font checksum mismatch'
    desktop=repo/'app/espdl-quickapp/overlay/apps/system/desktop'
    text=''.join(chr(c) for c in range(32,127))
    # Heading/UI coverage only; do not pull pronunciation dictionaries and
    # third-party app prose into the firmware. Dynamic names use the fallback.
    for path in [*desktop.glob('glass_*ui.inc'),desktop/'glass_i18n_catalog.h']:
        if path.exists():text+=path.read_text(encoding='utf-8')
    chars={ord(c) for c in text if 32<=ord(c)<127 or 0x3000<=ord(c)<=0x9fff}
    font=TTFont(a.source)
    options=subset.Options();options.hinting=False;options.layout_features=[]
    options.drop_tables+=['GSUB','GPOS','GDEF','kern']
    sub=subset.Subsetter(options=options);sub.populate(unicodes=chars);sub.subset(font)
    font=instantiateVariableFont(font,{'wght':700},inplace=True)
    font['OS/2'].usWeightClass=700
    for record in font['name'].names:
        value={1:'Vela Heading',2:'Bold',3:'VelaHeading-Bold',4:'Vela Heading Bold',6:'VelaHeading-Bold'}.get(record.nameID)
        if value:record.string=value.encode(record.getEncoding())
    target=desktop/'fonts/glass_heading-bold.ttf';font.save(target)
    (target.parent/'LICENSE-NotoSansSC.txt').write_bytes(a.license.read_bytes())
    data=target.read_bytes()
    out=['/* Generated by tools/generate_heading_font.py; SIL OFL in fonts/. */',
         'const unsigned char glass_heading_font_data[] = {']
    out+=['  '+','.join(f'0x{c:02x}' for c in data[i:i+24])+',' for i in range(0,len(data),24)]
    out+=['};','const size_t glass_heading_font_size=sizeof(glass_heading_font_data);','']
    (desktop/'glass_heading_data.inc').write_text('\n'.join(out),encoding='utf-8')
    print('Bold heading glyphs:',len(font.getBestCmap()),'bytes:',len(data))

if __name__=='__main__':main()
