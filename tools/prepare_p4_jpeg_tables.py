#!/usr/bin/env python3
"""Generate native standard JPEG tables from the pinned Espressif SDK source."""
from pathlib import Path
import argparse
import hashlib
import json
import re

p=argparse.ArgumentParser(description=__doc__)
p.add_argument('--sdk',type=Path,required=True)
p.add_argument('--output',type=Path,required=True)
a=p.parse_args()
source=a.sdk/'components/upper_hal_jpeg/jpeg_param.c'
raw=source.read_bytes();text=raw.decode('utf-8')
names={'zigzag_arr':64,'luminance_dc_coefficients':16,'luminance_dc_values':12,
 'luminance_ac_coefficients':16,'luminance_ac_values':162,
 'chrominance_dc_coefficients':16,'chrominance_dc_values':12,
 'chrominance_ac_coefficients':16,'chrominance_ac_values':162,
 'luminance_quantization_table':64,'chrominance_quantization_table':64}
arrays={}
for name,count in names.items():
 match=re.search(r'const uint(?:8|32)_t\s+'+name+r'\s*\[[^]]*\]\s*=\s*\{([^}]+)\};',text)
 assert match,name
 body=re.sub(r'/\*.*?\*/|//[^\n]*','',match[1],flags=re.S)
 values=[int(x.strip(),0) for x in body.split(',') if x.strip()]
 assert len(values)==count and all(0<=x<=255 for x in values),(name,len(values))
 arrays[name]=values
assert sorted(arrays['zigzag_arr'])==list(range(64))
for prefix in ['luminance','chrominance']:
 for kind in ['dc','ac']:
  assert sum(arrays[prefix+'_'+kind+'_coefficients'])==len(arrays[prefix+'_'+kind+'_values'])
lines=['/****************************************************************************',
 ' * arch/risc-v/src/esp32p4/esp32p4_jpeg_tables.h',' *',
 ' * SPDX-FileCopyrightText: 2024-2025 Espressif Systems (Shanghai) CO LTD',' *',
 ' * SPDX-License-Identifier: Apache-2.0',' ****************************************************************************/',
 '', '/* Generated by tools/prepare_p4_jpeg_tables.py from the pinned SDK',
 ' * upper_hal_jpeg/jpeg_param.c. Only standard table data is imported.',
 ' * SHA256: '+hashlib.sha256(raw).hexdigest(), ' */','',
 '#ifndef __ARCH_RISCV_SRC_ESP32P4_ESP32P4_JPEG_TABLES_H',
 '#define __ARCH_RISCV_SRC_ESP32P4_ESP32P4_JPEG_TABLES_H','',
 '/****************************************************************************',
 ' * Included Files',
 ' ****************************************************************************/','', '#include <stdint.h>','']
for name,values in arrays.items():
 lines += [f'static const uint8_t g_jpeg_{name}[{len(values)}] =','{']
 for i in range(0,len(values),12):lines.append('  '+', '.join(f'0x{x:02x}' for x in values[i:i+12])+',')
 lines += ['};','']
lines += ['#endif /* __ARCH_RISCV_SRC_ESP32P4_ESP32P4_JPEG_TABLES_H */','']
a.output.parent.mkdir(parents=True,exist_ok=True)
a.output.write_text('\n'.join(lines),encoding='utf-8')
print(json.dumps({'source_sha256':hashlib.sha256(raw).hexdigest(),
 'output_sha256':hashlib.sha256(a.output.read_bytes()).hexdigest(),'arrays':len(arrays)}))
