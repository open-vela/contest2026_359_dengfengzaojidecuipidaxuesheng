#!/usr/bin/env python3
"""Validate the English UI catalog and generate the compact firmware lookup."""
import argparse
import json
from pathlib import Path
import re


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args();repo=Path(__file__).resolve().parents[1]
    seen=set()
    def unique(pairs):
        result={}
        for key,value in pairs:
            if key in seen:raise ValueError('Duplicate translation: '+key)
            seen.add(key);result[key]=value
        return result
    catalog=json.loads((repo/'app/espdl-quickapp/i18n/en.json').read_text(encoding='utf-8'),object_pairs_hook=unique)
    # Keep argument count, order, length and conversion types exactly as C expects.
    printf=re.compile(r'%(?:[-+ #0]*\d*(?:\.\d+)?(?:hh|ll|[hljztL])?[diuoxXfFeEgGaAcspn]|%)')
    for source,english in catalog.items():
        assert isinstance(english,str) and english,source
        if printf.findall(source):assert printf.findall(source)==printf.findall(english),(source,english)
    rows=['/* SPDX-License-Identifier: Apache-2.0; generated by tools/generate_i18n.py */',
          '#ifndef GLASS_I18N_CATALOG_H','#define GLASS_I18N_CATALOG_H',
          'static const struct { const char *source,*english; } glass_english[] = {']
    for key in sorted(catalog,key=lambda s:s.encode('utf-8')):
        rows.append('  {'+json.dumps(key,ensure_ascii=False)+','+json.dumps(catalog[key],ensure_ascii=False)+'},')
    rows+=['};','#endif',''];text='\n'.join(rows)
    output=repo/'app/espdl-quickapp/overlay/apps/system/desktop/glass_i18n_catalog.h'
    if args.check:assert output.read_text(encoding='utf-8')==text,'Catalog header is stale'
    else:output.write_text(text,encoding='utf-8')
    print('I18N_CATALOG_OK',len(catalog),'entries')


if __name__=='__main__':main()
